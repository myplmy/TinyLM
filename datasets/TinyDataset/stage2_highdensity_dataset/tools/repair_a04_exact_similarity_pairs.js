const result = [];
for (const [versionText, rowsToRepair] of Object.entries(repairs)) {
  const version = Number(versionText);
  const file = path.join(sourceDir, `stage2_(14)state_transition_high_density_train_v${String(version).padStart(2, '0')}.source.jsonl`);
  const rows = fs.readFileSync(file, 'utf8').trimEnd().split(/\r?\n/).map(JSON.parse);
  for (const [lineText, text] of Object.entries(rowsToRepair)) {
    const line = Number(lineText);
    const row = rows[line - 1];
    if (!row || !text.includes(row.primary)) throw new Error(`${path.basename(file)}:${line} lost primary literal`);
    rows[line - 1] = { ...row, text };
    result.push({ version, line, primary: row.primary, text });
  }
  if (apply) fs.writeFileSync(file, rows.map(row => JSON.stringify(row)).join('\n') + '\n', 'utf8');
}
