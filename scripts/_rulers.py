def bpb_ruler(shape=None):
    """공통 원문 bpb 의 자. 형상을 알면 그 값, 모르면 전 계열 최대(보수).

    ★쓰는 법: 로그 val 효과를 공통 bpb 로 확인하려 할 때 **돌리기 전에**
    `효과(nats) / BPB_TO_NATS` 를 이 값과 견준다. 1배 미만이면 그 시험은 못 잰다
    (결과 075 §15.3 — 그래서 검정력 부족인 시험을 한 번 돌렸다).
    """
    v = BPB_BY_SHAPE.get(shape)
    # ★2026-09-08 — 🚫**0 을 자로 돌려주지 않는다.** `d16_cla2_norecur` 두 시드가
    #   소수 넷째까지 같아서 표에 0.00000 이 들어갔는데, 그것을 그대로 쓰면
    #   **어떤 차이도 유의**가 된다(함정 34 계열: 기준값이 틀린 쪽). n=2 에서 0 은
    #   "작다" 가 아니라 **"못 쟀다"** 다 -> 보수값으로 되돌린다.
    if not v:
        return BPB
    return v
