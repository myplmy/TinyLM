def cross(band_a: float, band_b: float) -> float:
    """★계열이 다른 두 모델을 비교할 때의 자 = **제곱합의 제곱근**.

    🚫2026-09-08 이전에는 `max(a, b)` 를 썼는데 **산술적으로 틀렸다**.
    band = 2σ 이고 Var(A−B) = σ_A² + σ_B² 이므로
    `2·sd(A−B) = sqrt(band_a² + band_b²)` 다. `max` 는 그보다 **작아서
    유의 판정을 남발하는 쪽**으로 틀린다(무재귀 0.0024 ↔ 재귀 0.0018 에서 25% 작다).
    ★같은 계열이면 두 값이 같으므로 `sqrt(2)·band` 가 되는데, 그때는 계열 자를
    **그대로** 쓴다 — 계열 자가 이미 "같은 계열 두 런의 차이" 로 정의됐기 때문이다.
    """
    return (band_a ** 2 + band_b ** 2) ** 0.5


